"""
The launcher submodule generates and runs the Reflex project behind
``reflex-langgraph ui``.

The UI needs no frontend code: :func:`run_ui` writes a small Reflex project into a
cache directory and runs it with ``reflex run``. What the page shows comes from the
backend's ``/health`` (:func:`fetch_health`, :func:`page_settings`). Nothing here
imports Reflex, so the command line stays fast for the other commands.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Optional, Union

import httpx

from .env import load_env_file
from .server.schemas import API_VERSION

#: Backend URL used when none is given.
DEFAULT_API = "http://localhost:8100"
#: The UI loads only these variables from a .env file: exactly the ones it reads.
UI_ENV = ("RLG_API_URL", "RLG_UI_")
#: Environment variable the generated app reads its page settings from.
CONFIG_ENV = "RLG_UI_CONFIG"
#: Name of the generated Reflex app.
APP_NAME = "rlg_ui"

RXCONFIG = '''\
# Generated by `reflex-langgraph ui`; rewritten on every start.
import json, os
import reflex as rx

_cfg = json.loads(os.environ.get("{env}") or "{{}}")
config = rx.Config(
    app_name="{app}",
    plugins=[
        rx.plugins.SitemapPlugin(),
        rx.plugins.RadixThemesPlugin(
            theme=rx.theme(accent_color=_cfg.get("accent", "indigo"), radius="large")),
    ],
)
'''.format(env=CONFIG_ENV, app=APP_NAME)

APP_MODULE = '''\
# Generated by `reflex-langgraph ui`; rewritten on every start.
import json, os
import reflex as rx

from reflex_langgraph.ui import add_agent_page

_cfg = json.loads(os.environ.get("{env}") or "{{}}")
app = rx.App()
add_agent_page(app, _cfg.get("title") or "reflex-langgraph", subtitle=_cfg.get("subtitle", ""),
               show_jobs=bool(_cfg.get("jobs")),
               placeholder=_cfg.get("placeholder") or "Ask anything",
               greeting=_cfg.get("greeting") or "What can I help with?",
               attachments=bool(_cfg.get("files")), max_file_mb=_cfg.get("max_file_mb") or 100,
               max_files=_cfg.get("max_files") or 30, file_types=_cfg.get("accept") or None)
'''.format(env=CONFIG_ENV)


class SettingsError(ValueError):
    """Raised when the built-in UI cannot serve a backend."""


def default_workdir() -> Path:
    """
    Return the default directory of the generated Reflex project.

    Returns
    -------
    pathlib.Path
        ``$XDG_CACHE_HOME/reflex-langgraph/ui``, or ``~/.cache/reflex-langgraph/ui``.
    """
    cache = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache")
    return cache / "reflex-langgraph" / "ui"


def load_ui_env(path: Union[str, Path] = ".env", *, required: bool = False) -> dict:
    """
    Load the UI's own settings from a .env file into the environment.

    Only ``RLG_API_URL`` and ``RLG_UI_*`` are read: the same file usually holds the
    backend's model API keys, which the UI process must not have. Variables already
    set in the environment win over the file.

    Parameters
    ----------
    path : str or pathlib.Path, default: '.env'
        The .env file.
    required : bool, default: False
        Raise when the file does not exist; otherwise a missing file loads nothing.

    Returns
    -------
    dict
        The variables taken from the file.

    Raises
    ------
    FileNotFoundError
        If ``required`` is true and the file does not exist.
    """
    path = Path(path)
    if required and not path.is_file():
        raise FileNotFoundError(f"no env file at {path}")
    return load_env_file(path, prefix=UI_ENV)


def fetch_health(api: str) -> dict:
    """
    Fetch a backend's ``/health``.

    Parameters
    ----------
    api : str
        Backend URL, e.g. ``http://localhost:8100``.

    Returns
    -------
    dict
        The health body: ``api`` (the contract version), ``title``, ``auth``, ``jobs``
        and ``approvals``.

    Raises
    ------
    httpx.HTTPError
        If the backend cannot be reached or answers with an error.
    """
    resp = httpx.get(api.rstrip("/") + "/health", timeout=5)
    resp.raise_for_status()
    return resp.json()


def page_settings(health: dict, *, title: Optional[str] = None,
                  subtitle: Optional[str] = None, placeholder: Optional[str] = None,
                  greeting: Optional[str] = None, jobs: Optional[bool] = None,
                  accent: str = "indigo") -> dict:
    """
    Decide the page settings from the backend's health and the given choices.

    Explicit choices win over what the backend reports.

    Parameters
    ----------
    health : dict
        The backend's ``/health`` body (see :func:`fetch_health`).
    title : str, optional
        Page title. By default, the backend's title.
    subtitle : str, optional
        Text under the title.
    placeholder : str, optional
        Hint text in the message box.
    greeting : str, optional
        Shown above the message box in an empty chat.
    jobs : bool, optional
        Show the jobs panel. By default, only when the backend has jobs.
    accent : str, default: 'indigo'
        Radix accent colour.

    Returns
    -------
    dict
        What the generated app reads: ``title``, ``subtitle``, ``placeholder``,
        ``greeting``, ``jobs``, ``accent``, and ``files``, ``max_file_mb``, ``max_files``
        and ``accept`` (from the backend: whether users may attach files, the limits and
        the formats).

    Raises
    ------
    SettingsError
        If the backend speaks another API version, or identifies callers with an
        auth hook (the built-in UI has no login).

    Examples
    --------

    >>> from reflex_langgraph.launcher import page_settings
    >>> health = {'api': 1, 'title': 'My agents', 'auth': 'none', 'jobs': True}
    >>> settings = page_settings(health)
    >>> settings['title'], settings['jobs']
    ('My agents', True)
    >>> page_settings(health, title='Lab assistant', jobs=False)['jobs']
    False
    """
    if health.get("api") != API_VERSION:
        raise SettingsError(f"the backend speaks API version {health.get('api')!r}, this UI "
                            f"speaks {API_VERSION}; install matching reflex-langgraph versions")
    if health.get("auth", "none") != "none":
        raise SettingsError(
            "the backend identifies callers with an auth hook (auth: external); the built-in "
            "UI has no login and sends no credentials. Run the backend without auth, or write "
            "your own Reflex app with reflex_langgraph.ui components.")
    return {
        "title": title if title is not None else health.get("title", "reflex-langgraph"),
        "subtitle": subtitle or "",
        "placeholder": placeholder or "",
        "greeting": greeting or "",
        "jobs": jobs if jobs is not None else bool(health.get("jobs")),
        "accent": accent,
        "files": bool(health.get("files")),
        "max_file_mb": int(health.get("max_file_mb") or 0),
        "max_files": int(health.get("max_files") or 0),
        "accept": health.get("accept") or {},
    }


def write_project(workdir: Union[str, Path]) -> None:
    """
    Write the generated Reflex project.

    The project is rewritten on every start; its ``.web`` directory is kept between
    runs as Reflex's build cache.

    Parameters
    ----------
    workdir : str or pathlib.Path
        Directory of the project.
    """
    workdir = Path(workdir)
    (workdir / APP_NAME).mkdir(parents=True, exist_ok=True)
    (workdir / "rxconfig.py").write_text(RXCONFIG)
    (workdir / APP_NAME / "__init__.py").write_text("")
    (workdir / APP_NAME / f"{APP_NAME}.py").write_text(APP_MODULE)


def reflex_command(*, port: int = 3000, backend_port: int = 8000,
                   backend_host: Optional[str] = None, single_port: bool = False,
                   prod: bool = False) -> list:
    """
    Build the ``reflex run`` command for the generated project.

    Parameters
    ----------
    port : int, default: 3000
        Frontend port.
    backend_port : int, default: 8000
        Port of Reflex's own backend (its websocket server).
    backend_host : str, optional
        Interface Reflex's backend binds to.
    single_port : bool, default: False
        Serve the frontend and Reflex's backend on one port (production builds only).
    prod : bool, default: False
        Run a production build instead of the dev server.

    Returns
    -------
    list of str
        The command, run with the current Python.

    Examples
    --------

    >>> from reflex_langgraph.launcher import reflex_command
    >>> reflex_command(port=3100)[2:]
    ['reflex', 'run', '--env', 'dev', '--frontend-port', '3100', '--backend-port', '8000']
    """
    cmd = [sys.executable, "-m", "reflex", "run", "--env", "prod" if prod else "dev",
           "--frontend-port", str(port), "--backend-port", str(backend_port)]
    if backend_host:
        cmd += ["--backend-host", backend_host]
    if single_port:
        cmd.append("--single-port")
    return cmd


def run_ui(api: str, settings: dict, *, workdir: Union[str, Path, None] = None,
           port: int = 3000, backend_port: int = 8000, backend_host: Optional[str] = None,
           public_url: Optional[str] = None, single_port: bool = False,
           prod: bool = False) -> int:
    """
    Write the Reflex project and run it until it exits.

    Parameters
    ----------
    api : str
        Backend URL, as seen from this machine.
    settings : dict
        Page settings (see :func:`page_settings`).
    workdir : str or pathlib.Path, optional
        Directory of the generated project. By default, :func:`default_workdir`.
    port, backend_port, backend_host, single_port, prod
        As in :func:`reflex_command`.
    public_url : str, optional
        URL the browser uses to reach Reflex's backend when it is not localhost,
        e.g. ``http://<public-ip>:8000``.

    Returns
    -------
    int
        Exit status of ``reflex run``; 130 when interrupted.
    """
    workdir = Path(workdir).expanduser().resolve() if workdir else default_workdir()
    write_project(workdir)
    if shutil.which("unzip") is None and not (workdir / ".web" / "node_modules").is_dir():
        print("note: reflex needs `unzip` on PATH to install its frontend tools on first run.",
              file=sys.stderr)
    env = {**os.environ, "RLG_API_URL": api, CONFIG_ENV: json.dumps(settings)}
    if public_url:
        env["REFLEX_API_URL"] = public_url
    print(f"UI for {api}: {json.dumps(settings)}\nproject: {workdir}", file=sys.stderr)
    command = reflex_command(port=port, backend_port=backend_port, backend_host=backend_host,
                             single_port=single_port, prod=prod)
    try:
        return subprocess.call(command, cwd=workdir, env=env)
    except KeyboardInterrupt:
        return 130
