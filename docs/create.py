"""
Generate the parts of the documentation that come from the code.

    python docs/create.py

writes ``api.rst`` (from the module docstrings) and ``cli.rst`` (from the commands'
``-h`` output). Run it after changing a docstring's first paragraph or a command's help;
``make html`` runs it too.
"""

import importlib
import pydoc
import subprocess
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
sys.path.insert(0, str(DOCS.parent))

from reflex_langgraph.cli import commands  # noqa: E402

credit = """..
   This file was automatically generated by docs/create.py.
"""

# Modules of the API page, by subpackage, in reading order.
SECTIONS = {
    "Configuration and settings": ["config", "env", "policy"],
    "Agents": ["agents.builder", "agents.tools", "agents.attachments", "agents.blocked",
               "agents.checkpoint"],
    "Jobs": ["jobs.spec", "jobs.runner", "jobs.progress", "jobs.tools", "jobs.router"],
    "Server": ["server.app", "server.store", "files", "server.stream", "server.events",
               "server.schemas"],
    "UI": ["ui.components", "ui.state", "ui.client", "ui.reducer", "launcher"],
}


def first_paragraph(module_name: str) -> str:
    doc = pydoc.getdoc(importlib.import_module(f"reflex_langgraph.{module_name}"))
    return doc.split("\n\n")[0].replace("\n", " ")


def run_help(*args: str) -> str:
    out = subprocess.run([sys.executable, "-m", "reflex_langgraph", *args, "-h"],
                         capture_output=True, text=True, check=True).stdout
    return "\n".join("   " + line if line else "" for line in out.splitlines())


# -- api.rst -------------------------------------------------------------------------

api = f"""{credit}
API
***

This page describes the application programming interface (API) of reflex-langgraph.

A backend needs only the names the package exports at its top level (``from
reflex_langgraph import ...``); the UI's names are in ``reflex_langgraph.ui``. Below is
the list of submodules:

"""
for section, modules in SECTIONS.items():
    api += f"**{section}**\n\n"
    for name in modules:
        api += f"- :mod:`{name} <reflex_langgraph.{name}>` : {first_paragraph(name)}\n"
    api += "\n"
api += """For getting help on a specific submodule (e.g. jobs.runner):

.. code:: python3

   from reflex_langgraph.jobs import runner
   help(runner)

"""
for section, modules in SECTIONS.items():
    api += f"{section}\n{'=' * len(section)}\n\n"
    for name in modules:
        api += f"{name}\n{'-' * len(name)}\n\n.. automodule:: reflex_langgraph.{name}\n   :members:\n\n"

(DOCS / "api.rst").write_text(api)

# -- cli.rst -------------------------------------------------------------------------

cli = f"""{credit}
CLI
***

This page describes the command line interface (CLI) of reflex-langgraph.

For getting help on the CLI:

.. code-block:: text

   $ reflex-langgraph -h

{run_help()}

For getting help on a specific command (e.g. ui):

.. code-block:: text

   $ reflex-langgraph ui -h

"""
for command in commands:
    cli += f"{command}\n{'=' * len(command)}\n\n.. code-block:: text\n\n"
    cli += f"   $ reflex-langgraph {command} -h\n\n{run_help(command)}\n\n"

(DOCS / "cli.rst").write_text(cli)
print(f"wrote {DOCS / 'api.rst'} and {DOCS / 'cli.rst'}")
